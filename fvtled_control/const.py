"""Constants for FVTLED BLE control."""

# BLE advertisement service UUID used by FVTLED devices for discovery
BLE_DISCOVERY_UUID = "00005a01-0000-1000-8000-00805f9b34fb"

# BLE device name prefix for FVTLED/MagicHome WiFi+BLE devices
BLE_NAME_PREFIX = "IOTWF"

# GATT service: primary control service (FFFF)
BLE_CONTROL_SERVICE_UUID = "0000ffff-0000-1000-8000-00805f9b34fb"

# Characteristics within the control service (FFFF)
BLE_WRITE_CHARACTERISTIC_UUID = "0000ff01-0000-1000-8000-00805f9b34fb"
BLE_NOTIFY_CHARACTERISTIC_UUID = "0000ff02-0000-1000-8000-00805f9b34fb"

# GATT service: secondary/status service (FE00)
BLE_STATUS_SERVICE_UUID = "0000fe00-0000-1000-8000-00805f9b34fb"

# Characteristics within the status service (FE00)
BLE_STATUS_WRITE_CHARACTERISTIC_UUID = "0000ff11-0000-1000-8000-00805f9b34fb"
BLE_STATUS_NOTIFY_CHARACTERISTIC_UUID = "0000ff22-0000-1000-8000-00805f9b34fb"

# Command bytes
CMD_POWER_ON = 0x23
CMD_POWER_OFF = 0x24
CMD_POWER_PREFIX = 0x71

CMD_COLOR_PREFIX = 0x31
CMD_COLOR_SUFFIX = 0xF0

CMD_STATUS_QUERY = bytes([0x81, 0x8A, 0x8B])

# Status response offsets
STATUS_POWER_INDEX = 2
STATUS_RED_INDEX = 6
STATUS_GREEN_INDEX = 7
STATUS_BLUE_INDEX = 8
STATUS_BRIGHTNESS_INDEX = 9

STATUS_POWER_ON_VALUE = 0x23
STATUS_POWER_OFF_VALUE = 0x24
